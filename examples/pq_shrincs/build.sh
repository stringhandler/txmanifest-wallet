#!/bin/sh
# Flatten src/shrincs_spend.simf and the vendored SHRINCS verifier into shrincs_spend.simf,
# the one file the manifest pins. Rerun after changing either, then `tx-manifest-wallet pin`.
# Needs mcpp (brew install mcpp; apt install mcpp); see
# contrib/shrincs-simplicity-verifier/README.md for why the preprocessor matters.
set -eu
cd "$(dirname "$0")"
# mcpp -P drops comments, so the header that says where the file comes from is added here.
{
  echo "// Generated by build.sh from src/shrincs_spend.simf and the vendored SHRINCS verifier. Do not edit."
  mcpp -P -I ../../contrib/shrincs-simplicity-verifier/upstream src/shrincs_spend.simf 2>/dev/null
} > shrincs_spend.simf
