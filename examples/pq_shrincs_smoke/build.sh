#!/bin/sh
# Flatten upstream's unmodified SHRINCS example into shrincs_main.simf, the one file the
# manifest pins. Rerun after updating the vendored verifier, then `tx-manifest-wallet pin`.
# Needs mcpp (brew install mcpp; apt install mcpp); see
# contrib/shrincs-simplicity-verifier/README.md for why the preprocessor matters.
set -eu
cd "$(dirname "$0")"
# mcpp -P drops comments, so the header that says where the file comes from is added here.
{
  echo "// Generated by build.sh from the vendored SHRINCS verifier's examples/shrincs/shrincs_main.simf. Do not edit."
  mcpp -P -I ../../contrib/shrincs-simplicity-verifier/upstream \
    ../../contrib/shrincs-simplicity-verifier/upstream/examples/shrincs/shrincs_main.simf 2>/dev/null
} > shrincs_main.simf
